import assert from 'node:assert/strict';
import {chromium} from 'playwright';

const base = process.env.INVENTORY_TEST_URL ?? 'http://127.0.0.1:5187';
const browser = await chromium.launch({channel: 'msedge', headless: true});
const errors = [];
try {
  const page = await browser.newPage({viewport: {width: 1440, height: 1100}});
  page.on('pageerror', error => errors.push(error.message));
  await page.request.post(`${base}/demo/sign-in/admin`);
  await page.goto(`${base}/dashboard`);
  await page.waitForFunction(() => !!JSON.parse(history.state?.userState ?? '{}').domainListEntry);
  const enter = async path => {
    await page.evaluate(path => Blazor.navigateTo(path), path);
    await page.waitForURL(`${base}${path}`);
    await page.getByText(path === '/baselines/domain' ? 'System-wide DMARC target' : 'Estate-wide sender decisions', {exact: true}).waitFor();
    await page.locator('.baseline-step').first().waitFor();
    assert.equal(await page.locator('.baseline-step').count(), 3);
  };
  const choosePolicy = async label => {
    await page.getByLabel('Policy (p)', {exact: true}).click();
    await page.getByRole('option', {name: label, exact: true}).click();
  };
  await page.evaluate(() => Blazor.navigateTo('/baselines'));
  await page.waitForURL(`${base}/baselines/domain`);
  await enter('/baselines/domain');
  const steps = page.locator('.baseline-step');
  assert((await steps.nth(0).innerText()).includes('Set the default'));
  assert((await steps.nth(1).innerText()).includes('Add exceptions only where needed'));
  assert((await steps.nth(2).innerText()).includes('Review and resolve gaps'));
  assert(!/\belse\s*\{/.test(await page.locator('.mud-main-content').innerText()));
  const system = steps.nth(0);
  const original = await system.locator('h6').last().innerText();
  await system.getByRole('button', {name: /default target/}).click();
  let dialog = page.getByRole('dialog');
  await dialog.waitFor();
  assert((await dialog.innerText()).includes('does not publish DNS'));
  const changedPolicy = original.includes('p=quarantine') ? 'Reject' : 'Quarantine';
  await choosePolicy(changedPolicy);
  await dialog.getByRole('button', {name: 'Save target', exact: true}).click();
  await dialog.waitFor({state: 'hidden'});
  await page.waitForFunction(policy => document.querySelector('.baseline-step').innerText.includes(`p=${policy}`), changedPolicy.toLowerCase());
  await system.getByRole('button', {name: 'Edit default target', exact: true}).click();
  await choosePolicy(original.includes('p=reject') ? 'Reject' : original.includes('p=quarantine') ? 'Quarantine' : original.includes('p=none') ? 'None' : 'No default target');
  await dialog.getByRole('button', {name: 'Save target', exact: true}).click();
  await dialog.waitFor({state: 'hidden'});
  await page.waitForFunction(target => [...document.querySelectorAll('.baseline-step h6')].some(node => node.innerText === target), original);
  assert.equal(await system.locator('h6').last().innerText(), original);
  await steps.nth(1).locator('summary').filter({hasText: /group targets and edit overrides/}).click();
  const groupOverride = steps.nth(1).getByRole('button', {name: /^Set override for /}).first();
  const groupName = (await groupOverride.getAttribute('aria-label')).replace('Set override for ', '');
  await groupOverride.click();
  await dialog.waitFor();
  assert((await dialog.innerText()).includes('group'));
  await choosePolicy('Reject');
  await dialog.getByRole('button', {name: 'Save target', exact: true}).click();
  await dialog.waitFor({state: 'hidden'});
  await steps.nth(1).getByRole('button', {name: `Edit override for ${groupName}`, exact: true}).click();
  await dialog.waitFor();
  await choosePolicy('Inherit system default');
  await dialog.getByRole('button', {name: 'Save target', exact: true}).click();
  await dialog.waitFor({state: 'hidden'});
  await steps.nth(1).getByRole('button', {name: `Set override for ${groupName}`, exact: true}).waitFor();
  await page.getByText('How targets are inherited', {exact: true}).click();
  assert(await page.getByText('Domain override → strictest target among its groups', {exact: false}).isVisible());
  await steps.nth(1).locator('summary').filter({hasText: /group targets and edit overrides/}).click();
  await page.getByText('How targets are inherited', {exact: true}).click();
  if (process.env.BASELINE_SCREENSHOT) await page.screenshot({path: process.env.BASELINE_SCREENSHOT, fullPage: true});

  await enter('/baselines/sender');
  assert((await steps.nth(0).innerText()).includes('Set default decisions'));
  assert((await steps.nth(1).innerText()).includes('Review undecided senders'));
  assert((await steps.nth(2).innerText()).includes('Add exceptions where needed'));
  await steps.nth(0).locator('summary').click();
  const setSender = steps.nth(0).getByRole('button', {name: /^Set decision for /}).first();
  const senderName = (await setSender.getAttribute('aria-label')).replace('Set decision for ', '');
  await setSender.click();
  await dialog.waitFor();
  assert(await dialog.getByRole('button', {name: 'Remove estate default', exact: true}).isDisabled());
  assert((await dialog.innerText()).includes('Estate-wide default'));
  await dialog.getByRole('radio', {name: /^Under review/}).check();
  await dialog.getByRole('button', {name: 'Save', exact: true}).click();
  await dialog.waitFor({state: 'hidden'});
  await steps.nth(0).getByRole('button', {name: `Edit decision for ${senderName}`, exact: true}).click();
  await dialog.waitFor();
  await dialog.getByRole('button', {name: 'Remove estate default', exact: true}).click();
  await dialog.waitFor({state: 'hidden'});
  await steps.nth(0).getByRole('button', {name: `Set decision for ${senderName}`, exact: true}).waitFor();
  const reviewHref = await page.getByRole('link', {name: 'Review outstanding sender decisions', exact: true}).getAttribute('href');
  assert.equal(reviewHref, '/dashboard?group=all&attention=senders');
  await page.evaluate(() => Blazor.navigateTo('/groups'));
  await page.getByRole('button', {name: 'Sender defaults', exact: true}).first().click();
  await page.waitForURL(target => /^\/groups\/\d+\/senders$/.test(target.pathname));
  await page.getByText('Sender decisions for this group', {exact: true}).waitFor();
  const groupId = new URL(page.url()).pathname.split('/')[2];
  assert.equal(await page.getByRole('link', {name: 'Review outstanding sender decisions', exact: true}).getAttribute('href'), `/dashboard?group=${groupId}&attention=senders`);
  await steps.nth(0).locator('summary').click();
  const groupSender = steps.nth(0).getByRole('button', {name: /^Set decision for /}).first();
  const groupSenderName = (await groupSender.getAttribute('aria-label')).replace('Set decision for ', '');
  await groupSender.click();
  await dialog.waitFor();
  assert((await dialog.innerText()).includes("this group's domains"));
  assert(await dialog.getByRole('button', {name: 'Restore inherited decision', exact: true}).isDisabled());
  await dialog.getByRole('radio', {name: /^Under review/}).check();
  await dialog.getByRole('button', {name: 'Save', exact: true}).click();
  await dialog.waitFor({state: 'hidden'});
  await steps.nth(0).getByRole('button', {name: `Edit decision for ${groupSenderName}`, exact: true}).click();
  await dialog.waitFor();
  await dialog.getByRole('button', {name: 'Restore inherited decision', exact: true}).click();
  await dialog.waitFor({state: 'hidden'});
  await steps.nth(0).getByRole('button', {name: `Set decision for ${groupSenderName}`, exact: true}).waitFor();
  await enter('/baselines/sender');
  await page.getByTitle('Toggle dark mode', {exact: true}).click();
  await page.waitForFunction(() => localStorage.getItem('dotmarc-dark-mode') === 'true');
  await page.setViewportSize({width: 390, height: 844});
  await page.reload();
  await page.getByText('Estate-wide sender decisions', {exact: true}).waitFor();
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  if (process.env.BASELINE_SENDER_SCREENSHOT) await page.screenshot({path: process.env.BASELINE_SENDER_SCREENSHOT, fullPage: true});
  await steps.nth(0).locator('summary').click();
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await page.goto(`${base}/dashboard`);
  await page.waitForFunction(() => !!JSON.parse(history.state?.userState ?? '{}').domainListEntry);
  await enter('/baselines/domain');
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  if (process.env.BASELINE_MOBILE_SCREENSHOT) await page.screenshot({path: process.env.BASELINE_MOBILE_SCREENSHOT, fullPage: true});
  await steps.nth(1).locator('summary').filter({hasText: /group targets and edit overrides/}).click();
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  assert.deepEqual(errors, []);
  console.log('Baselines flow browser checks passed: ordered steps, target save/restore, inheritance, sender save/reset, review links and mobile layout.');
} finally {
  await browser.close();
}
